test('grupo no padrão WhatsApp: regras, admins, remover e sair com avisos na conversa', async ({ page }) => {
  await page.addInitScript(() => localStorage.removeItem('hiadv-previa-ultima'))
  await page.goto('/experimentar'); await page.waitForURL(/seu-dia/)
  await page.getByRole('link', { name: /^Conversas/ }).first().click()
  await page.getByRole('button', { name: /Previdenciário/ }).first().click()
  await page.getByRole('button', { name: 'Dados do grupo', exact: true }).click()
  const d = page.getByRole('dialog', { name: 'Dados do grupo' })
  await expect(d.getByText('Casos de auxílio-acidente e B31 da equipe.')).toBeVisible()
  await expect(d.getByText('Admin do grupo')).toHaveCount(1)
  await d.getByRole('switch', { name: 'Só administradores enviam mensagens' }).check()
  await expect(d.getByText('Só administradores').first()).toBeVisible()
  await d.getByRole('button', { name: /Júlia Reis/ }).click()
  await d.getByRole('menuitem', { name: 'Tornar admin do grupo' }).click()
  await expect(d.getByText('Admin do grupo')).toHaveCount(2)
  await d.getByRole('button', { name: /Marcos Lima/ }).click()
  await d.getByRole('menuitem', { name: 'Remover do grupo' }).click()
  await expect(d.getByRole('alertdialog')).toContainText('Remover Marcos Lima do grupo?')
  await d.getByRole('button', { name: 'Confirmar' }).click()
  await expect(d.getByRole('button', { name: /Marcos Lima/ })).toHaveCount(0)
  await d.getByRole('button', { name: 'Editar nome e descrição' }).click()
  await d.getByLabel('Nome do grupo').fill('Previdenciário SC')
  await d.getByRole('button', { name: 'Salvar' }).click()
  await expect(d.getByRole('heading', { name: 'Previdenciário SC' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.keyboard.press('Escape')
  for (const t of ['definiu que só administradores enviam mensagens', 'Júlia Reis agora é administrador', 'removeu Marcos Lima', 'mudou o nome do grupo para "Previdenciário SC"'])
    await expect(page.getByRole('note').filter({ hasText: t })).toBeVisible()
  await page.getByRole('button', { name: 'Dados do grupo', exact: true }).click()
  await d.getByRole('button', { name: 'Sair do grupo' }).click()
  await d.getByRole('button', { name: 'Confirmar' }).click()
  await expect(page.getByRole('button', { name: /Previdenciário SC/ })).toHaveCount(0)
})
